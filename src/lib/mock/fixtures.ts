import type { FlavorId } from "@/lib/taste";
import type { DishData, MenuPage } from "@/lib/types";

const ZERO: Record<FlavorId, number> = {
  spicy: 0, cheesy: 0, creamy: 0, tangy: 0, sweet: 0, smoky: 0,
  garlicky: 0, herby: 0, crispy: 0, umami: 0, saucy: 0, nutty: 0,
};

type DishInput = Omit<DishData, "flavor" | "price_variants" | "confidence" | "confidence_reason" | "india_style_note" | "printed_description" | "familiar_comparison"> & {
  flavor: Partial<Record<FlavorId, number>>;
  price_variants?: DishData["price_variants"];
  printed_description?: string | null;
  familiar_comparison?: string | null;
  india_style_note?: string | null;
  confidence?: DishData["confidence"];
  confidence_reason?: string | null;
};

function dish(input: DishInput): DishData {
  return {
    printed_description: null,
    familiar_comparison: null,
    india_style_note: null,
    confidence: "high",
    confidence_reason: null,
    price_variants: [],
    ...input,
    flavor: { ...ZERO, ...input.flavor },
  };
}

